    fun byId(id: MoodId): MoodDefinition = all.first { it.id == id }

    private fun mood(
        id: MoodId,
        name: String,
        desc: String,
        start: Color,
        end: Color,
        genres: List<String>,
        terms: List<String>,
        bpmMin: Int,
        bpmMax: Int,
        anim: Float,
        weight: Float,
        empty: String,
    ): MoodDefinition =
        MoodDefinition(
            id = id,
            displayName = name,
            shortDescription = desc,
            gradientStart = start,
            gradientEnd = end,
            preferredGenres = genres,
            searchTerms = terms,
            bpmMin = bpmMin,
            bpmMax = bpmMax,
            animationIntensity = anim,
            recommendationWeight = weight,
            emptyStateCopy = empty,
        )
